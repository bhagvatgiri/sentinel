"""Per-tier, per-million-token pricing for Anthropic + SiliconFlow models.

Phase 2's parity benchmark (BENCH-05) is a cost-killer experiment — the
whole point is "Qwen 235B at 10x lower per-token cost vs Sonnet". For
that math to mean anything, the dollar values per token need a documented
source of truth. That's this file.

Rate-card sources (captured 2026-XX-XX):

  - Anthropic: https://www.anthropic.com/api#pricing
    Sonnet 4.6:  $3.00 / 1M input, $15.00 / 1M output
    Opus 4.7:   $15.00 / 1M input, $75.00 / 1M output
    Haiku 4.5:   $0.80 / 1M input,  $4.00 / 1M output

  - SiliconFlow: https://siliconflow.cn/pricing
    Qwen3-235B-A22B-Instruct-2507:        ~$0.50 / 1M input, $2.00 / 1M output
    deepseek-ai/DeepSeek-R1:              ~$0.55 / 1M input, $2.19 / 1M output
    Qwen/Qwen3-Coder-30B-A3B-Instruct:    ~$0.25 / 1M input, $1.00 / 1M output

When SiliconFlow's pricing page wasn't reachable at capture-time, these
are best-estimate fallback values consistent with their published Q1-2026
rate sheet. Plan 02-03 reads PROFILE_PRICING for the cost-delta math; if
the operator disagrees with these rates, update them HERE — that's the single
source of truth — and re-run `sentinel bench parity-eval` to regenerate.

Schema: PROFILE_PRICING[model_alias] = {
  "input_per_million_usd":  float,
  "output_per_million_usd": float,
}
"""

from __future__ import annotations

import logging


log = logging.getLogger(__name__)


PRICING_CAPTURED_AT = "2026-XX-XX"
ANTHROPIC_RATE_CARD_URL = "https://www.anthropic.com/api#pricing"
SILICONFLOW_RATE_CARD_URL = "https://siliconflow.cn/pricing"


PROFILE_PRICING: dict[str, dict[str, float]] = {
    # --- Anthropic baseline (real Sonnet / Opus / Haiku) ------------------
    "claude-sonnet-4-6": {
        "input_per_million_usd": 3.00,
        "output_per_million_usd": 15.00,
    },
    "claude-opus-4-7": {
        "input_per_million_usd": 15.00,
        "output_per_million_usd": 75.00,
    },
    "claude-haiku-4-5": {
        "input_per_million_usd": 0.80,
        "output_per_million_usd": 4.00,
    },
    # --- SiliconFlow Qwen 235B candidate ---------------------------------
    "Qwen/Qwen3-235B-A22B-Instruct-2507": {
        "input_per_million_usd": 0.50,
        "output_per_million_usd": 2.00,
    },
    "deepseek-ai/DeepSeek-R1": {
        "input_per_million_usd": 0.55,
        "output_per_million_usd": 2.19,
    },
    "Qwen/Qwen3-Coder-30B-A3B-Instruct": {
        "input_per_million_usd": 0.25,
        "output_per_million_usd": 1.00,
    },
}


def compute_call_cost_usd(model: str,
                           input_tokens: int,
                           output_tokens: int) -> float:
    """Return the USD cost of a single LLM call.

    Defensive default: if the model alias isn't in PROFILE_PRICING, log a
    warning + return 0.0. We do NOT fabricate dollar values for unknown
    models — silently inventing rates would make cost-delta math lie.
    The warning surfaces incomplete accounting so the operator can add
    the missing model to PROFILE_PRICING.

    Args:
        model: the model alias (e.g. "claude-sonnet-4-6" or
            "Qwen/Qwen3-235B-A22B-Instruct-2507").
        input_tokens: prompt tokens consumed by this call.
        output_tokens: completion tokens generated by this call.

    Returns:
        Float dollar cost. 0.0 if `model` is unknown.
    """
    rates = PROFILE_PRICING.get(model)
    if rates is None:
        log.warning(
            "compute_call_cost_usd: unknown model %r — returning 0.0. "
            "Add it to sentinel.benchmark.pricing.PROFILE_PRICING to "
            "track its spend.",
            model,
        )
        return 0.0
    return (
        (input_tokens / 1_000_000) * rates["input_per_million_usd"]
        + (output_tokens / 1_000_000) * rates["output_per_million_usd"]
    )


