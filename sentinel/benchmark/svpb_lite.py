"""D6 — SVPB-Lite published subset.

Replays the 10 publishable tasks in :mod:`svpb_lite_data`. Wraps SVPB's
replay harness with one extra guarantee: **deterministic seeding**.

Each task carries an integer ``seed`` that the replay runner is
expected to honor — given the same model + same seed, the same brief
must produce the same outcome (modulo network non-determinism that the
verifier is supposed to absorb). The unit tests assert this property.

The published numbers in research/svpb-lite-publish/RESULTS.md are
generated by running this module against multiple models and folding
the metrics into a comparison table.
"""

from __future__ import annotations

import logging
from typing import Callable, Optional

from sentinel.benchmark import svpb
from sentinel.benchmark.svpb_data import SVPBTaskRef
from sentinel.benchmark.svpb_lite_data import SVPBLiteTask, list_tasks


log = logging.getLogger(__name__)


def _to_svpb_taskref(t: SVPBLiteTask) -> SVPBTaskRef:
    """Adapter — reuse SVPB's replay path so we don't fork the harness."""
    return SVPBTaskRef(
        task_id=t.task_id,
        engagement=t.workspace,
        target=t.target,
        vuln_class=t.vuln_class,
        queue_index=t.queue_index,
        expected_outcome=t.expected_outcome,
        notes=t.notes,
        scope_yaml=t.scope_yaml,
    )


def _seeded_mock_runner(seed: int) -> Callable[[dict], dict]:
    """Stub runner whose output depends only on ``seed`` + the brief.

    Used by unit tests to prove determinism. A real benchmark run plugs
    in a Sentinel agent runner that respects the seed (sets random
    state, fixes RAG retrieval ordering, etc.).
    """
    def runner(brief: dict) -> dict:
        # Deterministic — perfect mock returns expected outcome with
        # tool-call counts derived from seed so per-seed identity is
        # provable.
        expected = (brief.get("expected_outcome") or "").lower()
        return {
            "verifier_outcome": expected,
            "model_self_claim": expected,
            "n_tool_calls": 3 + (seed % 3),
            "n_passing_tool_calls": 3 + (seed % 3),
            "evidence_quality_score": 0.85,
        }
    return runner


def run(
    *,
    model: str = "stub-model",
    runner_factory: Optional[Callable[[int], Callable[[dict], dict]]] = None,
    only_present: bool = True,
) -> dict:
    """Replay every SVPB-Lite task. Returns a dict with the same shape
    as :func:`sentinel.benchmark.svpb.run` plus a ``provenance`` block
    pointing at the scope yamls for re-runners.
    """
    runner_factory = runner_factory or _seeded_mock_runner
    tasks = list_tasks(only_present=only_present)
    results = []
    for t in tasks:
        task_ref = _to_svpb_taskref(t)
        runner = runner_factory(t.seed)
        results.append(svpb.replay_task(task_ref, model=model, runner=runner))
    agg = svpb.aggregate(results, total_tasks=len(tasks))
    out = {
        "benchmark": "svpb_lite",
        "model": model,
        "n_tasks": agg.n_tasks,
        "n_completed": agg.n_completed,
        "live_confirmed_rate": round(agg.live_confirmed_rate, 4),
        "live_disproven_rate": round(agg.live_disproven_rate, 4),
        "verification_error_rate": round(agg.verification_error_rate, 4),
        "tool_use_efficiency": (
            round(agg.tool_use_efficiency, 4)
            if agg.tool_use_efficiency is not None else None
        ),
        "per_task": [
            {
                "task_id": r.task_id,
                "expected": r.expected_outcome,
                "verifier": r.verifier_outcome,
                "model_self_claim": r.model_self_claim,
                "matched": r.matched_expected,
                "n_tool_calls": r.n_tool_calls,
            }
            for r in agg.per_task
        ],
        "provenance": [
            {
                "task_id": t.task_id,
                "program": t.program,
                "scope_yaml": t.scope_yaml,
                "seed": t.seed,
            }
            for t in tasks
        ],
    }
    return out
